A = 10
B = 20
sum = A + B    # = equals is a assignment operator
A += 10        # A = A + 10, this is called augmented assignment operator, it adds 10 to the value of A and assigns the result back to A.
B  -= 5        # B = B - 5, this is called augmented assignment operator, it subtracts 5 from the value of B and assigns the result back to B.
A *= 2         # A = A * 2, this is called augmented assignment operator, it multiplies the value of A by 2 and assigns the result back to A.
A /= 2         # A = A / 2, this is called augmented assignment operator, it divides the value of A by 2 and assigns the result back to A.
B %= 3         # B = B % 3, this is called augmented assignment operator
A **= 2   # A = A ** 2, this is called augmented assignment operator, it raises the value of A to the power of 2 and assigns the result back to A.
A //= 2        # A = A // 2, this is called augmented assignment
